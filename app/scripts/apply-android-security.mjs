/**
 * Re-applies the Android security hardening that `npx cap add android` wipes out.
 *
 * `android/` is generated and gitignored, so any hand edit to it is lost the moment the
 * native project is recreated. The two edits below are security-relevant, so "remember to
 * redo them" is not good enough - this script makes them mechanical and idempotent.
 *
 * What it enforces on android/app/src/main:
 *   1. <application android:allowBackup="false">                (Android 11 and below)
 *   2. <application android:dataExtractionRules="@xml/data_extraction_rules">
 *      + res/xml/data_extraction_rules.xml                      (Android 12+)
 *
 * Both are needed: targetSdk 31+ reads the rules file, older releases read allowBackup.
 * Without them the app's private data dir - the WebView cookie jar holding the live session
 * cookie, localStorage holding every tracker blob, and the service-worker cache - can leave
 * the device via cloud backup or device-to-device transfer. FiApp data already syncs through
 * the user's account, so a backup adds no recovery value and only widens exposure.
 *
 * Run it via `npm run sync` / `npm run add:android`, or on its own with `npm run harden`.
 * Safe to run any number of times: it is a no-op once the config is in place.
 *
 * NOT covered here (still manual, see README): strings.xml server_client_id, the
 * USE_BIOMETRIC permission, and the MainActivity text-zoom pin.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_DIR = dirname(dirname(fileURLToPath(import.meta.url)));
const MAIN = join(APP_DIR, 'android', 'app', 'src', 'main');
const MANIFEST = join(MAIN, 'AndroidManifest.xml');
const RULES = join(MAIN, 'res', 'xml', 'data_extraction_rules.xml');

const RULES_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- Android 12+ (targetSdk 31+) reads these instead of android:allowBackup. FiApp's private
     data dir holds the WebView cookie jar (the live session cookie), localStorage (every
     tracker blob) and the service-worker cache. None of that should leave the device via
     cloud backup or device-to-device transfer: the user's data already syncs through their
     account, so a backup adds no recovery value and only widens exposure.

     Generated by scripts/apply-android-security.mjs - edit the script, not this file. -->
<data-extraction-rules>
    <cloud-backup>
        <exclude domain="root" />
        <exclude domain="database" />
        <exclude domain="sharedpref" />
        <exclude domain="external" />
    </cloud-backup>
    <device-transfer>
        <exclude domain="root" />
        <exclude domain="database" />
        <exclude domain="sharedpref" />
        <exclude domain="external" />
    </device-transfer>
</data-extraction-rules>
`;

const ATTRS = [
  ['android:allowBackup', 'false'],
  ['android:dataExtractionRules', '@xml/data_extraction_rules'],
];

function fail(msg) {
  console.error(`apply-android-security: ${msg}`);
  process.exit(1);
}

if (!existsSync(MANIFEST)) {
  fail(`no manifest at ${MANIFEST}. Run \`npx cap add android\` first.`);
}

const changed = [];

mkdirSync(dirname(RULES), { recursive: true });
if (!existsSync(RULES) || readFileSync(RULES, 'utf8') !== RULES_XML) {
  writeFileSync(RULES, RULES_XML);
  changed.push('res/xml/data_extraction_rules.xml');
}

let manifest = readFileSync(MANIFEST, 'utf8');
const openTag = manifest.match(/<application\b[^>]*>/);
if (!openTag) fail('could not find the <application> tag in AndroidManifest.xml.');

let tag = openTag[0];
for (const [name, value] of ATTRS) {
  const existing = new RegExp(`\\s${name}="([^"]*)"`);
  const found = tag.match(existing);
  if (!found) {
    tag = tag.replace(/^<application/, `<application\n        ${name}="${value}"`);
    changed.push(`${name} added`);
  } else if (found[1] !== value) {
    tag = tag.replace(existing, ` ${name}="${value}"`);
    changed.push(`${name} was "${found[1]}", set to "${value}"`);
  }
}

if (tag !== openTag[0]) {
  manifest = manifest.replace(openTag[0], tag);
  writeFileSync(MANIFEST, manifest);
}

if (changed.length === 0) {
  console.log('apply-android-security: already hardened, nothing to do.');
} else {
  console.log('apply-android-security: applied ->\n  ' + changed.join('\n  '));
}
